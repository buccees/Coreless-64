"""Trusted simulation-to-ledger bridge for unique artifact sinking and recovery.

The simulation must call this bridge only after its authoritative state transition
confirms a submersible has sunk. Browser event payloads are not trusted inputs.
"""
from __future__ import annotations

from typing import Any

from .historical_artifact_store import HistoricalArtifactStore
from .sinking_event_registry import SinkingEventRegistry


class ArtifactSimulationBridge:
    """Turn a confirmed simulation sinking event into persistent artifact drops."""

    def __init__(self, *, artifact_store: HistoricalArtifactStore, sinking_registry: SinkingEventRegistry) -> None:
        if not isinstance(artifact_store, HistoricalArtifactStore):
            raise TypeError("artifact_store must be a HistoricalArtifactStore")
        if not isinstance(sinking_registry, SinkingEventRegistry):
            raise TypeError("sinking_registry must be a SinkingEventRegistry")
        self.artifact_store = artifact_store
        self.sinking_registry = sinking_registry

    def on_unit_sunk(self, world_seed: str, event: Any, authoritative_unit_state: Any) -> list[dict[str, Any]]:
        """Persist the confirmed sink position and drop all carried artifacts there.

        Event must be generated by trusted simulation code after the sinking
        transition. Repeated delivery is safe: after the first drop, no artifact
        remains carried by that unit.
        """
        record = self.sinking_registry.record_from_simulation(world_seed, event, authoritative_unit_state)
        return self.artifact_store.drop_all_on_sinking(
            world_seed, record["unit_id"], sinking_x=record["x"], sinking_y=record["y"],
            sink_event_authorized=True,
        )

    def on_replay_event(self, world_seed: str, replay_event: Any, authoritative_unit_state: Any) -> list[dict[str, Any]]:
        """Consume a provenance-bearing Coreless ReplayEvent from trusted simulation code."""
        from collections.abc import Mapping
        from .simulation import ReplayEvent

        if not isinstance(replay_event, ReplayEvent):
            raise TypeError("replay_event must be a Coreless ReplayEvent")
        if replay_event.kind != "UNIT_SUNK":
            raise ValueError("replay event must be UNIT_SUNK")
        provenance = replay_event.provenance
        if provenance is None or provenance.source_type != "simulation":
            raise ValueError("sinking replay event requires simulation provenance")
        if provenance.confidence is not None and provenance.confidence < 0.8:
            raise ValueError("sinking replay event confidence is too low")
        if not isinstance(replay_event.payload, Mapping):
            raise ValueError("sinking replay payload must be a mapping")
        event = dict(replay_event.payload)
        event["kind"] = "UNIT_SUNK"
        event["event_id"] = replay_event.event_id
        return self.on_unit_sunk(world_seed, event, authoritative_unit_state)
