const assert = require('node:assert/strict');
const core = require('../nirn-gravity-model.js');
const bodies = core.initialize();
const byId = Object.fromEntries(bodies.map(body => [body.id, body]));
assert.equal(bodies.length, 11);
assert.equal(byId.masser.parent, 'nirn');
assert.equal(byId.secunda.parent, 'nirn');
assert.equal(byId.stendarr.parent, 'julianos');
assert.equal(byId.dibella.parent, 'mara');
assert.deepEqual(core.collisions(bodies), []);
const acc = core.accelerations(bodies);
const dx = byId.masser.x - byId.nirn.x, dy = byId.masser.y - byId.nirn.y, dz = byId.masser.z - byId.nirn.z;
assert.ok(acc[0][0]*dx + acc[0][1]*dy + acc[0][2]*dz > 0);
const overlap = core.collisions([{id:'a',x:0,y:0,z:0,radius:10},{id:'b',x:15,y:0,z:0,radius:10}]);
assert.equal(overlap[0].status, 'COLLISION');
console.log('Nirn gravity tests passed: hierarchy, Newtonian attraction, initial clearance, physical-radius collision detection.');

const coupled = require('../nirn-coupled-world.js');
const nirn = byId.nirn;
const latitude = 0.41, longitude = -1.2, altitude = 0.012;
const localVelocity = { east: 125, north: -32, up: 4 };
const inertial = coupled.surfaceToInertial(nirn, latitude, longitude, altitude, localVelocity);
const recovered = coupled.inertialToSurface(nirn, inertial.position, inertial.velocity);
assert.ok(Math.abs(recovered.latitudeRad-latitude)<1e-10);
assert.ok(Math.abs(recovered.longitudeRad-longitude)<1e-10);
assert.ok(Math.abs(recovered.altitudeKm-altitude)<1e-8);
assert.ok(Math.abs(recovered.eastMps-localVelocity.east)<1e-7);
assert.ok(Math.abs(recovered.northMps-localVelocity.north)<1e-7);
assert.ok(Math.abs(recovered.upMps-localVelocity.up)<1e-7);
const surfaceG = coupled.effectiveSurfaceGravity(nirn,0,0,bodies);
assert.ok(surfaceG.magnitude>8 && surfaceG.magnitude<11, 'Nirn surface gravity should be Earth-like under the declared one-Earth-mass assumption');
const actor = coupled.createActor(nirn,0,0,0,{east:0,north:0,up:0});
const initialRadius = Math.hypot(actor.position.x-nirn.x,actor.position.y-nirn.y,actor.position.z-nirn.z);
coupled.stepActor(actor,bodies,0.1,{});
const afterRadius = Math.hypot(actor.position.x-nirn.x,actor.position.y-nirn.y,actor.position.z-nirn.z);
assert.ok(afterRadius>=nirn.radius-1e-7, 'surface contact must prevent an actor sinking through Nirn');
assert.ok(Math.abs(initialRadius-afterRadius)<1e-5);
console.log('Coupled world tests passed: inertial/surface transform round-trip, Earth-like local gravity, and surface contact.');
